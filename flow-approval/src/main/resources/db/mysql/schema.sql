-- MySQL 8 schema for flow-approval
CREATE TABLE IF NOT EXISTS flow_def (
    id             VARCHAR(64)  NOT NULL COMMENT '主键',
    rev            INT          DEFAULT 1 COMMENT '乐观锁版本',
    def_name       VARCHAR(200) NOT NULL COMMENT '流程名称',
    def_key        VARCHAR(100) NOT NULL COMMENT '流程定义 key',
    category       VARCHAR(100) DEFAULT NULL COMMENT '分类',
    description    VARCHAR(500) DEFAULT NULL COMMENT '描述',
    create_time    DATETIME     DEFAULT NULL,
    update_time    DATETIME     DEFAULT NULL,
    version        INT          NOT NULL DEFAULT 0 COMMENT '0=草稿，>=1=已发布',
    meta_info      VARCHAR(2000) DEFAULT NULL,
    deployment_id  VARCHAR(100) DEFAULT NULL,
    tenant_id      VARCHAR(64)  DEFAULT NULL,
    status         VARCHAR(20)  DEFAULT 'DRAFT' COMMENT 'DRAFT/PUBLISHED/SUSPENDED',
    bpmn_xml       LONGTEXT,
    svg_xml        LONGTEXT,
    deploy_time    DATETIME     DEFAULT NULL,
    PRIMARY KEY (id),
    KEY idx_flow_def_key (def_key, version),
    KEY idx_flow_def_deployment (deployment_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='流程模板与已发布定义';

CREATE TABLE IF NOT EXISTS flow_inst (
    id              VARCHAR(64)  NOT NULL,
    proc_inst_id    VARCHAR(64)  DEFAULT NULL,
    business_id     VARCHAR(100) DEFAULT NULL,
    business_key    VARCHAR(200) DEFAULT NULL,
    task_id         VARCHAR(500) DEFAULT NULL,
    task_name       VARCHAR(500) DEFAULT NULL,
    start_user_id   VARCHAR(64)  DEFAULT NULL,
    start_user_name VARCHAR(100) DEFAULT NULL,
    start_depart    VARCHAR(64)  DEFAULT NULL,
    start_role      VARCHAR(500) DEFAULT NULL,
    start_time      DATETIME     DEFAULT NULL,
    end_time        DATETIME     DEFAULT NULL,
    title           VARCHAR(500) DEFAULT NULL,
    state           VARCHAR(10)  DEFAULT '1' COMMENT '1运行中/2已完成/3已终止/4已撤销',
    tenant_id       VARCHAR(64)  DEFAULT NULL,
    ext_id          VARCHAR(100) DEFAULT NULL,
    def_id          VARCHAR(64)  DEFAULT NULL,
    def_key         VARCHAR(100) DEFAULT NULL,
    def_name        VARCHAR(200) DEFAULT NULL,
    url             VARCHAR(500) DEFAULT NULL,
    variables       LONGTEXT,
    active_tokens   LONGTEXT,
    activities      LONGTEXT,
    PRIMARY KEY (id),
    KEY idx_flow_inst_business_key (business_key),
    KEY idx_flow_inst_start_user (start_user_id, state),
    KEY idx_flow_inst_def (def_key, def_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='流程实例与业务主表';

CREATE TABLE IF NOT EXISTS flow_task (
    id                VARCHAR(64)  NOT NULL,
    inst_id           VARCHAR(64)  NOT NULL,
    def_id            VARCHAR(64)  DEFAULT NULL,
    task_def_key      VARCHAR(100) DEFAULT NULL,
    name              VARCHAR(200) DEFAULT NULL,
    assignee          VARCHAR(64)  DEFAULT NULL,
    candidate_users   VARCHAR(1000) DEFAULT NULL,
    candidate_groups  VARCHAR(1000) DEFAULT NULL,
    owner             VARCHAR(64)  DEFAULT NULL,
    delegation_state  VARCHAR(20)  DEFAULT NULL,
    form_key          VARCHAR(200) DEFAULT NULL,
    priority          INT          DEFAULT NULL,
    status            VARCHAR(20)  DEFAULT NULL COMMENT 'ACTIVE/COMPLETED/CANCELED',
    token_id          VARCHAR(64)  DEFAULT NULL,
    start_time        DATETIME     DEFAULT NULL,
    claim_time        DATETIME     DEFAULT NULL,
    end_time          DATETIME     DEFAULT NULL,
    duration          BIGINT       DEFAULT NULL,
    delete_reason     VARCHAR(500) DEFAULT NULL,
    parent_task_id    VARCHAR(64)  DEFAULT NULL,
    tenant_id         VARCHAR(64)  DEFAULT NULL,
    PRIMARY KEY (id),
    KEY idx_flow_task_inst (inst_id, status),
    KEY idx_flow_task_assignee (assignee, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='流程任务与审批历史';

CREATE TABLE IF NOT EXISTS flow_comment (
    id            VARCHAR(64)   NOT NULL,
    inst_id       VARCHAR(64)   NOT NULL,
    task_id       VARCHAR(64)   DEFAULT NULL,
    task_def_key  VARCHAR(100)  DEFAULT NULL,
    task_name     VARCHAR(200)  DEFAULT NULL,
    comment_type  VARCHAR(20)   DEFAULT NULL COMMENT 'comment/back/jump/cancel/terminal/system',
    user_id       VARCHAR(64)   DEFAULT NULL,
    user_name     VARCHAR(100)  DEFAULT NULL,
    message       VARCHAR(2000) DEFAULT NULL,
    flow_state    VARCHAR(10)   DEFAULT NULL,
    create_time   DATETIME      DEFAULT NULL,
    PRIMARY KEY (id),
    KEY idx_flow_comment_inst (inst_id, create_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='审批记录';

CREATE TABLE IF NOT EXISTS sys_user (
    id          VARCHAR(64)  NOT NULL,
    username    VARCHAR(64)  NOT NULL,
    password    VARCHAR(64)  DEFAULT NULL,
    realname    VARCHAR(100) DEFAULT NULL,
    avatar      VARCHAR(500) DEFAULT NULL,
    email       VARCHAR(100) DEFAULT NULL,
    phone       VARCHAR(32)  DEFAULT NULL,
    dept_id     VARCHAR(64)  DEFAULT NULL,
    role_codes  VARCHAR(500) DEFAULT NULL COMMENT ',admin,manager,',
    leader_id   VARCHAR(64)  DEFAULT NULL,
    status      INT          DEFAULT 1,
    create_time DATETIME     DEFAULT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_sys_user_username (username)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='简化用户表';
